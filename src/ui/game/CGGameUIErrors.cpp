char CGGameUI::s_lastError[3000];

// ref: FUN_005216f0
// Every client-side game error (ERR_INV_FULL and the 729 others) comes through here with the
// format arguments its GlobalString wants. The reference also plays the entry's sound kit or
// error speech (SI2::PlaySound / FUN_00986d00), which waits on the sound port; the chat kind
// needs CGChat::AddMessage (FUN_00509dd0), also not ported yet.
void CGGameUI::DisplayError(uint32_t errorCode, ...) {
    if (errorCode >= sizeof(s_gameErrors) / sizeof(s_gameErrors[0])) {
        return;
    }

    if (errorCode == 0xB) {
        // TODO ShowTutorial(0x39) (FUN_00530840): the bag-full tutorial
    }

    const GameErrorEntry& entry = s_gameErrors[errorCode];

    if (entry.speech == 0x44) {
        if (entry.sound && SStrCmpI(entry.sound, "NONE", 0x7FFFFFFF)) {
            // TODO SI2::PlaySound(entry.sound) (FUN_004c74a0)
        }
    } else {
        // TODO error speech (FUN_00986d00, gated by Sound_EnableErrorSpeech)
    }

    if (!entry.stringId || !*entry.stringId) {
        return;
    }

    // The reference resolves the text through the player's gender when a player is active
    // (FUN_007225e0) and plainly otherwise; frozen's GetText takes the gender directly
    const char* format = FrameScript_GetText(entry.stringId, -1, GENDER_NOT_APPLICABLE);

    char text[3000];
    va_list args;
    va_start(args, errorCode);
    SStrVPrintf(text, sizeof(text), format, args);
    va_end(args);

    SStrCopy(s_lastError, text, sizeof(s_lastError));

    switch (entry.kind) {
    case 0:
        // TODO CGChat::AddMessage(text, entry.chatType, ...) (FUN_00509dd0)
        return;
    case 1:
        if (text[0]) {
            FrameScript_SignalEvent(188 /* UI_INFO_MESSAGE */, "%s", text);
        }
        break;
    case 2:
        if (text[0]) {
            FrameScript_SignalEvent(187 /* UI_ERROR_MESSAGE */, "%s", text);
        }
        break;
    case 3:
        ConsoleWriteA(text, static_cast<COLOR_T>(3));
        break;
    }
}
